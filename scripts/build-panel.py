"""Compile packaged HTML/CSS to DOM data. No HTML parser or eval runs in the browser."""
import json
from html.parser import HTMLParser
from pathlib import Path

root = Path(__file__).resolve().parent.parent

class PanelParser(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.nodes = []
        self.stack = []
        self.in_body = False
        self.skip_script = False

    def handle_starttag(self, tag, attrs):
        if tag == 'body':
            self.in_body = True
            return
        if not self.in_body:
            return
        if tag == 'script':
            self.skip_script = True
            return
        if self.skip_script:
            return
        node = {'tag': tag, 'attrs': {k: v or '' for k, v in attrs}, 'children': []}
        (self.stack[-1]['children'] if self.stack else self.nodes).append(node)
        if tag not in ('input', 'meta', 'link', 'br', 'hr', 'img'):
            self.stack.append(node)

    def handle_endtag(self, tag):
        if tag == 'script':
            self.skip_script = False
        elif tag == 'body':
            self.in_body = False
        elif self.in_body and self.stack and self.stack[-1]['tag'] == tag:
            self.stack.pop()

    def handle_data(self, text):
        if self.in_body and not self.skip_script and text.strip():
            (self.stack[-1]['children'] if self.stack else self.nodes).append(text)

parser = PanelParser()
parser.feed((root / 'extension/panel.html').read_text('utf-8'))
payload = {'nodes': parser.nodes, 'css': (root / 'extension/panel.css').read_text('utf-8')}
(root / 'extension/panel-template.js').write_text(
    '// Generated by scripts/build-panel.py from panel.html and panel.css.\n'
    'globalThis.__GMGN_AGENT_TEMPLATE__ = ' + json.dumps(payload, ensure_ascii=False) + ';\n', encoding='utf-8')
print('Built extension/panel-template.js')
